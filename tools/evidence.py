def _v(x) -> str:
    if isinstance(x, (tuple, list, np.ndarray)):
        return "(" + ", ".join(_v(float(e)) for e in x) + ")"
    x = float(x)
    if math.isnan(x):
        return "NaN"
    r = round(x, 12)
    return f"{r + 0.0:.6g}"



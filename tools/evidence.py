"""Evidence tables for the docs, generated from the repository itself.

Subcommands (each writes a generated Markdown file under ``docs/evidence/``;
``--check`` regenerates into memory and fails if the committed file differs):

* ``findings``: for every finding about the saved models in
  ``docs/PYTHON_PORT.md``, the exact lines of the ``.mdl`` files, the
  committed spec digest (``docs/spec``) and the chart code that show it, with
  line numbers and links. Deterministic, no tools needed.
* ``chains``: the block chains ported from block parameters (convention
  correction, conditioning, Threshold, home pose, joystick, comm-loss
  display), run on the inputs of ``tests/test_blocks.py``; the table is what
  the port outputs. Deterministic, no tools needed.
* ``nan-hold``: the NaN-hold reproduction. The same input rows go through the
  Python grid manager and through Octave running the model's chart code
  (``tools/octave/parity_driver.m``); the table is the desired pose both
  produce. Needs ``octave-cli``.
* ``checks``: runs the Octave-side checks (original MATLAB tests, chart code
  vs ``matlab/phase*.txt`` templates, fixture regeneration) and
  ``tools/mdl_spec.py --check``, and records the tool versions and the
  result lines. Needs ``octave-cli``; output depends on the Octave version.
* ``interop``: captures real traffic: the unmodified
  ``python/yolo_pad_direct_stream_fresh.py`` fed frames over TCP (fresh, then
  frozen), with every 48-byte observation it publishes, and a
  ``qautoland loopback``-style run with one 112-byte command and the 8-byte
  echo. Needs the vision extras; timestamps differ per run, so it has no
  ``--check``. Data: ``docs/figures/data/interop.json``.

Usage::

    python tools/evidence.py findings [--check]
    python tools/evidence.py chains [--check]
    python tools/evidence.py nan-hold [--check]
    python tools/evidence.py checks
    python tools/evidence.py interop [--render]   # --render: rewrite the tables from interop.json
"""

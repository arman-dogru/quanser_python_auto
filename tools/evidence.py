def _rel(path: str) -> str:
    return "../../" + path


def _excerpt(path: str, pattern: str, before: int = 0, after: int = 0, nth: int = 0, width: int = 160) -> str:
    """Markdown for the lines around the ``nth`` match of ``pattern`` in ``path``."""
    lines = (ROOT / path).read_text(encoding="utf-8", errors="replace").splitlines()
    hits = [i for i, ln in enumerate(lines) if re.search(pattern, ln)]
    if len(hits) <= nth:
        raise SystemExit(f"{path}: pattern {pattern!r} not found")
    i = hits[nth]
    lo, hi = max(0, i - before), min(len(lines), i + after + 1)
    body = "\n".join(f"{k + 1:6d}  {lines[k][:width]}{' ...' if len(lines[k]) > width else ''}" for k in range(lo, hi))
    rng = f"L{lo + 1}" if hi - lo == 1 else f"L{lo + 1}-L{hi}"
    return f"[`{path}` {rng.replace('-', '–')}]({_rel(path)}#{rng})\n\n```text\n{body}\n```\n"



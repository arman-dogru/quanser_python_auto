function build_phase7_constant_altitude_centering(doBuild)
%BUILD_PHASE7_CONSTANT_ALTITUDE_CENTERING Add guarded vision XY centering.
% Creates a new Mission Server. It does not modify Phase 6 or Commander.
% No descent or LAND trigger is introduced.

if nargin < 1, doBuild = false; end
projectRoot = fileparts(fileparts(mfilename('fullpath')));
modelDir = fullfile(projectRoot, 'simulink');
sourceFile = fullfile(modelDir, 'Mission_Server_QDrone_YOLO_Interrupt.mdl');
targetFile = fullfile(modelDir, 'Mission_Server_QDrone_YOLO_Centering.mdl');
sourceModel = 'Mission_Server_QDrone_YOLO_Interrupt';
targetModel = 'Mission_Server_QDrone_YOLO_Centering';
cfg = config_autonomous();

assert(isfile(sourceFile), 'Working Phase 6 Mission Server missing: %s', sourceFile);
for name = {sourceModel,targetModel}
    if bdIsLoaded(name{1}), close_system(name{1},0); end
end
load_system(sourceFile);
save_system(sourceModel,targetFile);
close_system(sourceModel,0);
load_system(targetFile);

mission = firstBlock(targetModel,'MISSION SERVER');
missionName = getfullname(mission);
grid = firstBlock(mission,'Grid Search Manager');
confirm = firstBlock(mission,'YOLO Confirmation and Hover Hold');
setConfirmationScript(confirm,cfg);
setCenteringGridScript(grid,cfg);

safeAddLine(mission,confirm,4,grid,6);
safeAddLine(mission,confirm,5,grid,7);
safeAddLine(mission,confirm,6,grid,8);

addDisplay(missionName,'Centering Active Display',[1510 650 1600 680]);
addDisplay(missionName,'Pad Centered Display',[1510 695 1600 725]);
addDisplay(missionName,'Pixel Error Display',[1510 740 1620 785]);
safeAddLine(mission,grid,5,[missionName '/Centering Active Display'],1);
safeAddLine(mission,grid,6,[missionName '/Pad Centered Display'],1);
safeAddLine(mission,grid,7,[missionName '/Pixel Error Display'],1);

set_param(targetModel,'SimulationCommand','update');
fprintf('Updated model: %s\n',targetModel);
if doBuild, slbuild(targetModel); end
save_system(targetModel,targetFile);
fprintf('\nPhase 7 Mission Server created in:\n%s\n',targetFile);
fprintf('Use with QDrone_YOLO_Direct_Stream_Commander.\n');
fprintf('Constant altitude only: no descent or automatic LAND logic exists.\n');
end

function setConfirmationScript(block,cfg)
chart = find(sfroot,'-isa','Stateflow.EMChart','Path',getfullname(block));
assert(~isempty(chart),'YOLO confirmation MATLAB Function not found.');
chart.Script = sprintf([ ...
'function [confirmedPad,holdPose,confidence,padU,padV,newPadSample] = fcn(measuredPose,vision,newVision,clockTime,triggers)\n' ...
'%%#codegen\n' ...
'persistent good bad active captured lastFrame lastFresh latestU latestV\n' ...
'if isempty(good), good=uint8(0); bad=uint8(0); active=false; captured=zeros(4,1); lastFrame=-1; lastFresh=-1; latestU=0; latestV=0; end\n' ...
'takeoff=triggers(2)>0.5; newPadSample=false;\n' ...
'if ~takeoff, good=uint8(0); bad=uint8(0); active=false; lastFresh=clockTime; end\n' ...
'if takeoff && newVision && vision(5)~=lastFrame\n' ...
' lastFrame=vision(5); lastFresh=clockTime; valid=vision(1)>0.5 && vision(4)>=%0.6f && vision(2)>=0 && vision(2)<=640 && vision(3)>=0 && vision(3)<=480;\n' ...
' if valid, latestU=vision(2); latestV=vision(3); newPadSample=true; bad=uint8(0); if good<uint8(%d),good=good+uint8(1);end; if ~active && good>=uint8(%d),active=true;captured=measuredPose;end\n' ...
' else, good=uint8(0); if bad<uint8(%d),bad=bad+uint8(1);end; if active && bad>=uint8(%d),active=false;end; end\n' ...
'end\n' ...
'if active && (lastFresh<0 || clockTime-lastFresh>%0.6f),active=false;good=uint8(0);bad=uint8(0);end\n' ...
'confirmedPad=active;holdPose=captured;confidence=vision(4);padU=latestU;padV=latestV;\n' ...
'end\n'],cfg.yoloConfidence,cfg.yoloConfirmFrames,cfg.yoloConfirmFrames, ...
cfg.yoloReleaseFrames,cfg.yoloReleaseFrames,cfg.yoloStaleSeconds);
end

function setCenteringGridScript(block,cfg)
chart = find(sfroot,'-isa','Stateflow.EMChart','Path',getfullname(block));
assert(~isempty(chart),'Grid Search Manager MATLAB Function not found.');
wps=mat2str(cfg.waypoints,6); map=mat2str(cfg.pixelToWorldAtSearchHeight,8);
target=mat2str(cfg.visionTargetPixel,6);
chart.Script = sprintf([ ...
'function [desiredPose,waypointIndex,gridComplete,visitedCount,centeringActive,centered,pixelError] = fcn(measuredPose,homePose,triggers,confirmedPad,holdPose,padU,padV,newPadSample)\n' ...
'%%#codegen\n' ...
'persistent stage dwell takeoffWasLow reverseOrder complete visited sessionActive centerMode centerPose centerOrigin centerGood\n' ...
'if isempty(stage),stage=uint8(0);dwell=uint16(0);takeoffWasLow=true;reverseOrder=false;complete=false;visited=uint8(0);sessionActive=false;centerMode=false;centerPose=zeros(4,1);centerOrigin=zeros(2,1);centerGood=uint8(0);end\n' ...
'takeoff=triggers(2)>0.5; wps=%s; target=%s; map=%s; pixelError=[padU-target(1);padV-target(2)];\n' ...
'if ~takeoff,stage=uint8(0);dwell=uint16(0);takeoffWasLow=true;reverseOrder=false;sessionActive=false;centerMode=false;centerGood=uint8(0);\n' ...
'elseif ~sessionActive,complete=false;visited=uint8(0);sessionActive=true;end\n' ...
'if confirmedPad && ~centerMode,centerMode=true;centerPose=holdPose;centerPose(3)=%0.6f;centerOrigin=holdPose(1:2);centerGood=uint8(0);end\n' ...
'desiredPose=homePose;desiredPose(3)=%0.6f;\n' ...
'if centerMode\n' ...
' desiredPose=centerPose;\n' ...
' if newPadSample\n' ...
'  if norm(pixelError)<=%0.6f,if centerGood<uint8(%d),centerGood=centerGood+uint8(1);end;\n' ...
'  else,centerGood=uint8(0);bodyStep=map*pixelError;a=measuredPose(4)-(%0.8f);R=[cos(a) -sin(a);sin(a) cos(a)];step=R*bodyStep;n=norm(step);if n>%0.6f,step=step*(%0.6f/n);end;candidate=centerPose(1:2)+step;offset=candidate-centerOrigin;on=norm(offset);if on>%0.6f,candidate=centerOrigin+offset*(%0.6f/on);end;centerPose(1)=min(max(candidate(1),%0.6f),%0.6f);centerPose(2)=min(max(candidate(2),%0.6f),%0.6f);end\n' ...
' end\n' ...
' desiredPose=centerPose;\n' ...
'elseif takeoff && takeoffWasLow\n' ...
' eHome=measuredPose(1:3)-desiredPose(1:3);if norm(eHome)<=0.12,dwell=dwell+uint16(1);if dwell>=uint16(100),dFirst=measuredPose(1:2)-wps(1,1:2);dLast=measuredPose(1:2)-wps(20,1:2);reverseOrder=sum(dLast.*dLast)<sum(dFirst.*dFirst);stage=uint8(1);dwell=uint16(0);takeoffWasLow=false;end;else,dwell=uint16(0);end\n' ...
'elseif takeoff && stage>=1\n' ...
' idx=double(stage);if reverseOrder,idx=21-idx;end;desiredPose(1:3)=wps(idx,:);e=measuredPose(1:3)-desiredPose(1:3);if norm(e)<=0.12,dwell=dwell+uint16(1);if dwell>=uint16(100),visited=stage;if stage<uint8(20),stage=stage+uint8(1);else,complete=true;end;dwell=uint16(0);end;else,dwell=uint16(0);end\n' ...
'end\n' ...
'waypointIndex=0;if stage>=uint8(1),waypointIndex=double(stage);if reverseOrder,waypointIndex=21-waypointIndex;end;end;gridComplete=complete;visitedCount=double(visited);centeringActive=centerMode;centered=centerGood>=uint8(%d);\n' ...
'end\n'],wps,target,map,cfg.searchHeight,cfg.searchHeight, ...
cfg.centerPixelTolerance,cfg.centerDwellFrames,cfg.visionCalibrationYaw,cfg.centerMaxStep, ...
cfg.centerMaxStep,cfg.centerMaxDisplacement,cfg.centerMaxDisplacement, ...
cfg.xLimits(1),cfg.xLimits(2),cfg.yLimits(1),cfg.yLimits(2),cfg.centerDwellFrames);
end

function block=firstBlock(system,fragment)
blocks=find_system(system,'FindAll','on','SearchDepth',1,'Type','Block');
blocks(blocks==get_param(system,'Handle'))=[]; match=false(size(blocks));
for k=1:numel(blocks),match(k)=contains(get_param(blocks(k),'Name'),fragment,'IgnoreCase',true);end
blocks=blocks(match);assert(~isempty(blocks),'Block containing "%s" not found.',fragment);block=blocks(1);
end

function addDisplay(system,name,position)
path=[system '/' name]; h=getSimulinkBlockHandle(path,false);if h~=-1,delete_block(path);end
add_block('simulink/Sinks/Display',path,'Position',position);
end

function safeAddLine(system,sourceBlock,sourcePort,destBlock,destPort)
sh=get_param(sourceBlock,'PortHandles');dh=get_param(destBlock,'PortHandles');
old=get_param(dh.Inport(destPort),'Line');if old~=-1,delete_line(old);end
add_line(getfullname(system),sh.Outport(sourcePort),dh.Inport(destPort),'autorouting','on');
end

function build_milestone5_yolo_interrupt(doBuild)
%BUILD_MILESTONE5_YOLO_INTERRUPT Add a confirmed YOLO hover interrupt.
% This builder starts from the protected, flight-tested grid-search pair.
% It creates NEW model names and never overwrites that baseline.
%
% The camera is allowed to freeze DesiredPose at the measured pose only.
% It cannot generate XY corrections and it cannot initiate descent.

if nargin < 1
    doBuild = false;
end

hostModel = 'Mission_Server_QDrone_YOLO_Interrupt';
commanderModel = 'QDrone_YOLO_Interrupt_Commander';
for name = {hostModel, commanderModel}
    if bdIsLoaded(name{1}), close_system(name{1}, 0); end
end

projectRoot = fileparts(fileparts(mfilename('fullpath')));
modelDir = fullfile(projectRoot, 'simulink');
% Read the known-working pair in place and save only under new names. A
% separate immutable copy also exists under backups/ in the development
% package, but it does not need to be copied into the live project.
hostSource = fullfile(modelDir, 'Mission_Server_QDrone_Grid_Search.mdl');
commanderSource = fullfile(modelDir, 'QDrone_Grid_Search_Commander.mdl');
hostTarget = fullfile(modelDir, [hostModel '.mdl']);
commanderTarget = fullfile(modelDir, [commanderModel '.mdl']);
cfg = config_autonomous();

assert(isfile(hostSource), 'Working host baseline is missing: %s', hostSource);
assert(isfile(commanderSource), 'Working Commander baseline is missing: %s', commanderSource);

cloneModel(hostSource, hostTarget);
cloneModel(commanderSource, commanderTarget);
configureHost(hostModel, hostTarget, cfg);

updateModel(hostModel);
updateModel(commanderModel);
if doBuild
    slbuild(hostModel);
    slbuild(commanderModel);
end
save_system(hostModel);
save_system(commanderModel);
fprintf('\nPhase 6 YOLO-interrupt models created in:\n%s\n', modelDir);
fprintf('Protected grid-search backup was not modified.\n');
end

function cloneModel(sourceFile, targetFile)
[~, sourceName] = fileparts(sourceFile);
if bdIsLoaded(sourceName), close_system(sourceName, 0); end
load_system(sourceFile);
save_system(sourceName, targetFile);
close_system(sourceName, 0);
end

function configureHost(model, targetFile, cfg)
mission = firstBlock(model, 'MISSION SERVER');
missionName = getfullname(mission);
gridManager = firstBlock(mission, 'Grid Search Manager');
measurement = firstBlock(mission, 'Measurement Conditioning');
joystick = firstBlock(mission, 'JOYSTICK');

% Basic Stream Client is non-blocking at the Simulink interface and
% reconnects automatically if Python is started after the Mission Server.
receiver = add_block('quarc_library/Communications/Basic/Stream Client', ...
    [missionName '/YOLO Observation TCP Client'], ...
    'Position', [870 330 1030 410]);
% Use QUARC's stable mask parameter identifiers. Dialog prompt wording has
% changed between QUARC releases, while these identifiers are also used in
% Quanser's own example model files.
% Run the block interface at the Mission Server base rate. The actual
% socket receive operation remains in QUARC's separate blocking thread.
% This avoids an unsafe cross-task signal between 20 ms and base-rate logic;
% the `new` output still changes only when a fresh packet arrives.
set_param(receiver, ...
    'uri_source', 'Specify via dialog (do not evaluate)', ...
    'uri', sprintf('tcpip://localhost:%d', cfg.yoloTcpPort), ...
    'send_options', 'Do not send data', ...
    'receive_options', 'Receive most recent data', ...
    'default_value', '[0 0 0 0 -1 0]', ...
    'sample_time', 'qc_get_step_size', ...
    'optimization', 'Minimum latency', ...
    'implementation', 'Use blocking I/O in a separate thread');

% With sending disabled, Stream Client outputs are state, err, rcv, new.
ports = get_param(receiver, 'PortHandles');
assert(numel(ports.Outport) >= 4, ...
    'YOLO Stream Client did not expose state, err, rcv and new outputs.');

clockBlock = add_block('simulink/Sources/Clock', ...
    [missionName '/YOLO Freshness Clock'], 'Position', [885 430 915 450]);
confirmation = add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [missionName '/YOLO Confirmation and Hover Hold'], ...
    'Position', [1070 320 1280 435]);
setConfirmationScript(confirmation, cfg);

safeAddLine(mission, measurement, 1, confirmation, 1);
safeAddLineByHandle(missionName, ports.Outport(3), confirmation, 2);
safeAddLineByHandle(missionName, ports.Outport(4), confirmation, 3);
safeAddLine(mission, clockBlock, 1, confirmation, 4);
safeAddLine(mission, joystick, 1, confirmation, 5);

% Add confirmedPad and holdPose to the existing grid manager. When active,
% its stage and dwell counters are frozen and DesiredPose is the captured
% measured pose. Hence detection cannot move the vehicle toward the pad.
setInterruptibleGridScript(gridManager, cfg.waypoints);
safeAddLine(mission, confirmation, 1, gridManager, 4);
safeAddLine(mission, confirmation, 2, gridManager, 5);

padDisplay = add_block('simulink/Sinks/Display', ...
    [missionName '/YOLO Confirmed Hover Display'], ...
    'Position', [1295 330 1375 360]);
confidenceDisplay = add_block('simulink/Sinks/Display', ...
    [missionName '/YOLO Confidence Display'], ...
    'Position', [1295 375 1375 405]);
safeAddLine(mission, confirmation, 1, padDisplay, 1);
safeAddLine(mission, confirmation, 3, confidenceDisplay, 1);

save_system(model, targetFile);
end

function setConfirmationScript(block, cfg)
chart = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', getfullname(block));
assert(~isempty(chart), 'YOLO confirmation MATLAB Function was not created.');
chart.Script = sprintf([ ...
    'function [confirmedPad, holdPose, confidence] = fcn(measuredPose, vision, newVision, clockTime, triggers)\n' ...
    '%%#codegen\n' ...
    'persistent good bad active captured lastFrame lastFreshTime\n' ...
    'if isempty(good)\n' ...
    '    good=uint8(0); bad=uint8(0); active=false; captured=zeros(4,1); lastFrame=-1.0; lastFreshTime=-1.0;\n' ...
    'end\n' ...
    'takeoff = triggers(2) > 0.5;\n' ...
    'if ~takeoff\n' ...
    '    good=uint8(0); bad=uint8(0); active=false; lastFreshTime=clockTime;\n' ...
    'end\n' ...
    'if takeoff && newVision && vision(5) ~= lastFrame\n' ...
    '    lastFrame=vision(5); lastFreshTime=clockTime;\n' ...
    '    valid = vision(1)>0.5 && vision(4)>=%0.6f && vision(2)>=0.0 && vision(2)<=640.0 && vision(3)>=0.0 && vision(3)<=480.0;\n' ...
    '    if valid\n' ...
    '        bad=uint8(0); if good<uint8(%d), good=good+uint8(1); end\n' ...
    '        if ~active && good>=uint8(%d), active=true; captured=measuredPose; end\n' ...
    '    else\n' ...
    '        good=uint8(0); if bad<uint8(%d), bad=bad+uint8(1); end\n' ...
    '        if active && bad>=uint8(%d), active=false; end\n' ...
    '    end\n' ...
    'end\n' ...
    'if active && (lastFreshTime<0.0 || clockTime-lastFreshTime>%0.6f), active=false; good=uint8(0); bad=uint8(0); end\n' ...
    'confirmedPad=active; holdPose=captured; confidence=vision(4);\n' ...
    'end\n'], cfg.yoloConfidence, cfg.yoloConfirmFrames, ...
    cfg.yoloConfirmFrames, cfg.yoloReleaseFrames, cfg.yoloReleaseFrames, ...
    cfg.yoloStaleSeconds);
end

function setInterruptibleGridScript(block, gridWaypoints)
chart = find(sfroot, '-isa', 'Stateflow.EMChart', 'Path', getfullname(block));
assert(~isempty(chart), 'Grid Search Manager MATLAB Function was not found.');
wps = mat2str(gridWaypoints, 6);
chart.Script = sprintf([ ...
    'function [desiredPose, waypointIndex, gridComplete, visitedCount] = fcn(measuredPose, homePose, triggers, confirmedPad, holdPose)\n' ...
    '%%#codegen\n' ...
    'persistent stage dwell takeoffWasLow reverseOrder complete visited sessionActive\n' ...
    'if isempty(stage), stage=uint8(0); dwell=uint16(0); takeoffWasLow=true; reverseOrder=false; complete=false; visited=uint8(0); sessionActive=false; end\n' ...
    'takeoff=triggers(2)>0.5;\n' ...
    'if ~takeoff, stage=uint8(0); dwell=uint16(0); takeoffWasLow=true; reverseOrder=false; sessionActive=false;\n' ...
    'elseif ~sessionActive, complete=false; visited=uint8(0); sessionActive=true; end\n' ...
    'wps=%s; desiredPose=homePose; desiredPose(3)=0.70;\n' ...
    'if confirmedPad && takeoff\n' ...
    '    desiredPose=holdPose;\n' ...
    'elseif takeoff && takeoffWasLow\n' ...
    '    eHome=measuredPose(1:3)-desiredPose(1:3);\n' ...
    '    if sqrt(sum(eHome.*eHome))<=0.12, dwell=dwell+uint16(1);\n' ...
    '        if dwell>=uint16(100), dFirst=measuredPose(1:2)-wps(1,1:2); dLast=measuredPose(1:2)-wps(20,1:2); reverseOrder=sum(dLast.*dLast)<sum(dFirst.*dFirst); stage=uint8(1); dwell=uint16(0); takeoffWasLow=false; end\n' ...
    '    else, dwell=uint16(0); end\n' ...
    'elseif takeoff && stage>=1\n' ...
    '    idx=double(stage); if reverseOrder, idx=21.0-idx; end; desiredPose(1:3)=wps(idx,:); e=measuredPose(1:3)-desiredPose(1:3);\n' ...
    '    if sqrt(sum(e.*e))<=0.12, dwell=dwell+uint16(1);\n' ...
    '        if dwell>=uint16(100), visited=stage; if stage<uint8(20), stage=stage+uint8(1); else, complete=true; end; dwell=uint16(0); end\n' ...
    '    else, dwell=uint16(0); end\n' ...
    'end\n' ...
    'waypointIndex=0.0; if stage>=uint8(1), waypointIndex=double(stage); if reverseOrder, waypointIndex=21.0-waypointIndex; end; end\n' ...
    'gridComplete=complete; visitedCount=double(visited);\n' ...
    'end\n'], wps);
end

function updateModel(model)
load_system(model);
set_param(model, 'SimulationCommand', 'update');
fprintf('Updated model: %s\n', model);
end

function block = firstBlock(system, fragment)
blocks = find_system(system, 'FindAll', 'on', 'SearchDepth', 1, 'Type', 'Block');
blocks(blocks == get_param(system, 'Handle')) = [];
match = false(size(blocks));
for k=1:numel(blocks), match(k)=contains(get_param(blocks(k),'Name'),fragment,'IgnoreCase',true); end
blocks = blocks(match);
assert(~isempty(blocks), 'Block containing "%s" not found under %s.', fragment, system);
block = blocks(1);
end

function safeAddLine(system, sourceBlock, sourcePort, destBlock, destPort)
sourceHandles = get_param(sourceBlock, 'PortHandles');
safeAddLineByHandle(getfullname(system), sourceHandles.Outport(sourcePort), destBlock, destPort);
end

function safeAddLineByHandle(systemName, sourceHandle, destBlock, destPort)
destHandles = get_param(destBlock, 'PortHandles');
oldLine = get_param(destHandles.Inport(destPort), 'Line');
if oldLine ~= -1, delete_line(oldLine); end
add_line(systemName, sourceHandle, destHandles.Inport(destPort), 'autorouting', 'on');
end
